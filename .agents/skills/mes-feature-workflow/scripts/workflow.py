class GateError(Exception):
    pass


def canonical(data):
    return json.dumps(data, sort_keys=True, ensure_ascii=False, separators=(',', ':')).encode('utf-8')


def digest(data):
    return hashlib.sha256(canonical(data)).hexdigest()


def file_hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8-sig'))


def write_json(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def now():
    return datetime.now(timezone.utc).isoformat()


def require(condition, message):
    if not condition:
        raise GateError(message)


def signer_config(kind, private=False):
    prefix = 'MES_WORKFLOW_' + kind.upper()
    name = prefix + ('_PRIVATE_KEY' if private else '_SIGNERS')
    path = os.environ.get(name, '')
    require(path and Path(path).is_file(), f'DEPENDENCY_NOT_READY: {name} not configured')
    return path


def seal(payload, kind):
    payload = dict(payload, principal=os.environ.get('MES_WORKFLOW_' + kind.upper() + '_PRINCIPAL', ''))
    require(payload['principal'], f'{kind}: signer principal missing')
    result = subprocess.run(['ssh-keygen', '-Y', 'sign', '-f', signer_config(kind, True), '-n', 'mes-workflow-' + kind, '-'], input=canonical(payload), capture_output=True)
    require(result.returncode == 0, f'{kind}: signing failed')
    return {'payload': payload, 'signature': result.stdout.decode('utf-8')}


def unseal(record, kind):
    require(isinstance(record, dict) and 'payload' in record and 'signature' in record, f'{kind}: unsigned record')
    with tempfile.TemporaryDirectory(prefix='mes-signature-') as temporary:
        signature = Path(temporary) / 'record.sig'
        signature.write_text(record['signature'], encoding='utf-8')
        principal = record['payload'].get('principal', '')
        require(principal, f'{kind}: principal missing')
        result = subprocess.run(['ssh-keygen', '-Y', 'verify', '-f', signer_config(kind), '-I', principal, '-n', 'mes-workflow-' + kind, '-s', str(signature)], input=canonical(record['payload']), capture_output=True)
        require(result.returncode == 0, f'{kind}: invalid signature/untrusted signer')
    return record['payload']


def junit(path):
    tree = ET.parse(path)
    cases = list(tree.getroot().iter('testcase'))
    require(bool(cases), 'JUnit has no actual test cases')
    failed = sum(c.find('failure') is not None or c.find('error') is not None for c in cases)
    skipped = [c.get('classname', '') + '.' + c.get('name', '') for c in cases if c.find('skipped') is not None]
    return {'tests': len(cases), 'failed': failed, 'skipped': skipped}


class Workflow:
    def __init__(self, root, feature, simulation=False):
        self.root = Path(root).resolve()
        require(re.fullmatch(r'[A-Z][A-Z0-9-]{2,63}', feature), 'Invalid feature ID')
        self.feature = feature
        self.dir = self.root / 'docs/features' / feature
        self.path = self.dir / 'workflow.yaml'
        self.data = load_json(self.path)
        self.simulation = simulation
        require(self.data.get('feature') == feature and self.data.get('schema') == 2, 'Feature/schema mismatch')
        if self.data.get('simulation'):
            require(simulation and feature.startswith('WF-TEST-') and self.root != ROOT and not (self.root / '.git').exists(), 'Simulation records cannot accept real MES features')
        require(not simulation or self.data.get('simulation') is True, 'Simulation must be explicitly labelled')

    def resolve(self, name):
        require(isinstance(name, str) and name and not Path(name).is_absolute(), 'Evidence path must be repository-relative')
        path = (self.root / name).resolve()
        require(path.is_relative_to(self.root), 'Path escapes repository')
        require(path.is_file(), f'Missing file: {name}')
        return path

    def ref(self, ref):
        require(isinstance(ref, dict) and ref.get('version'), 'Artifact version missing')
        path = self.resolve(ref.get('path'))
        require(ref.get('sha256') == file_hash(path), f'Artifact hash mismatch: {ref.get("path")}')
        return path

    def stage(self, gate):
        require(gate in self.data.get('stages', {}), f'Missing stage {gate}')
        stage = self.data['stages'][gate]
        require(stage.get('status') in STATES, f'Invalid status for {gate}')
        return stage

    def subject(self, gate):
        stages = {}
        for current in GATES[:GATES.index(gate) + 1]:
            stages[current] = {k: v for k, v in self.stage(current).items() if k not in ('status', 'approval', 'runs')}
        return digest({'schema': 2, 'feature': self.feature, 'simulation': self.data.get('simulation', False), 'scope': self.data.get('scope'), 'reads': self.data.get('reads'), 'stages': stages})

    def record(self, path, kind):
        payload = unseal(load_json(self.resolve(path)), kind)
        require(payload.get('feature') == self.feature and payload.get('simulation', False) == self.data.get('simulation', False), 'Record feature/simulation mismatch')
        require(payload.get('timestamp'), 'Record timestamp missing')
        return payload

    def approval(self, gate, path=None, decision='ACCEPTED'):
        payload = self.record(path or self.stage(gate).get('approval'), 'approval')
        require(payload.get('gate') == gate and payload.get('decision') == decision, 'Approval gate/decision mismatch')
        require(payload.get('subject') == self.subject(gate), 'Approval is stale: version/hash or contract changed')
        require(payload.get('approver') and payload.get('authority') in ('human', 'delegated-authority'), 'Invalid approval authority')
        self.ref(payload.get('source'))
        if payload.get('authority') == 'delegated-authority':
            require(payload.get('delegation_source'), 'Delegated authority requires verifiable delegation source')
            self.ref(payload['delegation_source'])
        return payload

    def common(self, gate):
        for name in MANDATORY_READS:
            require(name in self.data.get('reads', {}), f'Missing read record: {name}')
            self.ref(self.data['reads'][name])
        scope = self.data.get('scope', {})
        require(scope.get('requirements') and scope.get('write_paths'), 'Requirements/write scope missing')
        require(scope.get('baseline') == 'FINAL BASELINE COMPLETE v1.0.23' and scope.get('ui') == 'Global UI V2', 'Authority mismatch')
        require(scope.get('mode') in ('full', 'simplified'), 'Unknown workflow mode')
        for read in self.data['reads'].values():
            self.ref(read)
        require(all(isinstance(p, str) and p and p not in ('*', '**', '**/*') and '..' not in Path(p).parts and not Path(p).is_absolute() for p in scope['write_paths']), 'Unsafe write scope')
        if scope.get('mode') == 'simplified':
            require(scope.get('risk') == 'low' and scope.get('reason'), 'Simplification requires low risk and reason')
            self.approval('G1', scope.get('simplification_approval'), 'SIMPLIFICATION')
        if gate != 'G1':
            previous = GATES[GATES.index(gate) - 1]
            require(self.stage(previous)['status'] == 'ACCEPTED', f'{previous} is not ACCEPTED')
            self.check(previous)

    def artifact_checks(self, gate):
        stage = self.stage(gate)
        required = ARTIFACTS[gate]
        if self.data['scope'].get('mode') == 'simplified' and gate in ('G1', 'G2', 'G3'):
            # Approved exemption is still represented by artifacts and human confirmation;
            # no skipped gate or direct transition to G4 is possible.
            required = ('task_card', 'exemption_review')
        for name in required:
            require(name in stage.get('artifacts', {}), f'{gate}: missing artifact {name}')
        for ref in stage.get('artifacts', {}).values():
            self.ref(ref)
        require(not stage.get('blockers'), f'{gate}: unresolved blockers')
        require(stage.get('commit') and stage.get('version'), f'{gate}: commit/version missing')
        if not self.simulation:
            result = subprocess.run(['git', 'cat-file', '-e', stage['commit'] + '^{commit}'], cwd=self.root, capture_output=True)
            require(result.returncode == 0, f'{gate}: Git commit is not resolvable')
        # Bind input/test source contents; never trust a copied passed=true result.
        require(stage.get('source_files'), f'{gate}: source/test input manifest missing')
        for ref in stage['source_files']:
            self.ref(ref)

    def suites(self, gate):
        required = list(SUITES[gate])
        if self.data['scope'].get('menu') and gate == 'G5':
            required.append('menu-authorization')
        if self.data['scope'].get('mode') == 'simplified' and gate in ('G1', 'G2', 'G3'):
            required = ['scope-review']
        plans = self.stage(gate).get('test_plans', {})
        for name in required:
            require(name in plans, f'{gate}: required suite {name} missing')
        for name, plan in plans.items():
            require(plan.get('argv') and isinstance(plan['argv'], list) and plan.get('timeout_seconds', 0) > 0, f'Invalid test plan {name}')
            receipt_path = self.stage(gate).get('runs', {}).get(name)
            require(receipt_path, f'{gate}: no executed evidence for {name}')
            receipt = self.record(receipt_path, 'evidence')
            require(receipt.get('gate') == gate and receipt.get('suite') == name, 'Suite association mismatch')
            require(receipt.get('subject') == self.subject(gate) and receipt.get('plan_hash') == digest(plan), f'{name}: stale execution evidence')
            require(receipt.get('exit_code') == 0, f'{name}: command failed')
            require(receipt.get('duration_seconds', -1) >= 0 and receipt.get('argv') and receipt.get('started'), 'Execution provenance missing')
            for ref in receipt.get('outputs', []):
                self.ref(ref)
            require(len(receipt.get('outputs', [])) >= 2, 'JUnit/log evidence missing')
            stats = junit(self.ref(receipt['junit']))
            require(stats == receipt.get('result') and stats['failed'] == 0, f'{name}: test failures/result mismatch')
            if stats['skipped']:
                waiver = self.approval(gate, plan.get('skip_approval'), 'SKIP_EXCEPTION')
                require(waiver.get('suite') == name and waiver.get('cases') == stats['skipped'] and waiver.get('reason'), 'Skip exception does not cover cases')
            environment = receipt.get('environment', {})
            require(environment.get('kind') == plan.get('environment'), f'{name}: environment mismatch')
            if gate == 'G2' and name in ('prototype-browser', 'prototype-console', 'prototype-visual') or gate == 'G4' and name == 'api-wiring' or gate == 'G5' and name in ('api-integration', 'real-business', 'browser-e2e', 'visual-comparison', 'role-permission', 'menu-authorization'):
                require(environment.get('kind') == 'local-real', f'{name}: mocks cannot count as runtime acceptance')
                require(environment.get('frontend') == ('http://localhost:5174' if gate == 'G2' else 'http://localhost:5173'), 'Wrong frontend runtime')
                if gate in ('G4', 'G5'):
                    require(environment.get('backend') == 'http://localhost:8080', 'Wrong backend runtime')

    def document(self, gate, name):
        return load_json(self.ref(self.stage(gate)['artifacts'][name]))

    def design(self):
        mapping = self.document('G1', 'page_mapping')
        pages = mapping.get('pages', [])
        require(pages and all(p.get('template') in ('T1', 'T2', 'T3', 'T4', 'T5', 'T6') and p.get('id') for p in pages), 'Illegal or missing T1–T6 template')
        covered = {r for p in pages for r in p.get('requirements', [])}
        require(set(self.data['scope']['requirements']) <= covered, 'UI design does not cover requirements')
        require(all(p.get('fields') and p.get('buttons') is not None and p.get('states') and p.get('label_control') == 'same-row' and p.get('viewports') and p.get('tokens') for p in pages), 'Page fields/buttons/states/horizontal labels/responsive/tokens missing')

    def prototype(self):
        proto = self.document('G2', 'prototype_manifest')
        require(proto.get('stack') == ['Vue 3', 'TypeScript', 'Vite', 'Ant Design Vue', 'Pinia', 'Vue Router'], 'Prototype stack must be Vue contract')
        require(proto.get('root') == str(PROTOTYPE).replace('\\', '/') or self.simulation and proto.get('root') == 'SIMULATION/mes-demo', 'Wrong prototype source location')
        require(proto.get('files') and proto.get('tree_sha256') == digest(proto['files']), 'Prototype file/hash manifest missing')
        require(all(re.fullmatch(r'[0-9a-f]{64}', h) for h in proto['files'].values()), 'Invalid prototype source hashes')
        require(proto.get('page_sources') and proto.get('mock_adapter'), 'Prototype page mapping/Mock adapter missing')
        pages = self.document('G1', 'page_mapping')['pages']
        require(all(p['id'] in proto['page_sources'] and proto['page_sources'][p['id']] in proto['files'] for p in pages), 'Prototype source mapping does not cover approved pages')
        if not proto.get('commit'):
            self.approval('G2', proto.get('hash_exception'), 'PROTOTYPE_HASH_EXCEPTION')
        if not self.simulation and not os.environ.get('GITHUB_ACTIONS'):
            for name, sha in proto['files'].items():
                path = (PROTOTYPE / name).resolve()
                require(path.is_relative_to(PROTOTYPE.resolve()) and path.is_file() and file_hash(path) == sha, 'Prototype source changed/missing')
            if proto.get('commit'):
                require(subprocess.run(['git', 'cat-file', '-e', proto['commit'] + '^{commit}'], cwd=PROTOTYPE, capture_output=True).returncode == 0, 'Prototype commit not resolvable')
        screenshots = self.document('G2', 'screenshots')
        require(set(screenshots.get('viewports', [])) >= {1440, 1280, 900, 375} and screenshots.get('pairs'), 'Required matching viewport screenshot comparison missing')
        for pair in screenshots['pairs']:
            self.ref(pair['reference'])
            self.ref(pair['rendered'])
            require(pair.get('viewport') in screenshots['viewports'] and pair.get('review'), 'Screenshot pair review missing')
        required_pairs = {(p['id'], v) for p in pages for v in set(p['viewports']) | {1440, 1280, 900, 375}}
        require(required_pairs <= {(p.get('page'), p.get('viewport')) for p in screenshots['pairs']}, 'Prototype screenshot pairs do not cover every page/viewport')

    def contracts(self):
        contracts = self.document('G3', 'contracts')
        fields = contracts.get('fields', [])
        require(bool(fields), 'Critical field definitions missing')
        ids = set()
        for field in fields:
            require(all(k in field for k in FIELD_KEYS), 'Incomplete field-level design')
            require(field['id'] not in ids, 'Duplicate field ID')
            ids.add(field['id'])
            expected = {k: field[k] for k in ('type', 'length', 'precision', 'required')}
            for layer in ('page', 'database', 'api'):
                require(contracts.get('projections', {}).get(layer, {}).get(field['id']) == expected, f'Field/API/DB conflict: {field["id"]}/{layer}')
        operations = contracts.get('operations', [])
        require(bool(operations), 'Operation contract missing')
        for operation in operations:
            require(all(operation.get(k) for k in ('id', 'page_button', 'permission', 'backend_permission', 'api', 'state_validation', 'data_validation', 'success', 'failure', 'test_cases')), 'Incomplete operation/permission contract')
            require(operation['permission'] == operation['backend_permission'], 'Button/backend permission mismatch')
            require(not operation.get('write') or operation.get('role') != 'view', 'Read-only permission grants write')
        require(contracts.get('states') == contracts.get('backend_states') and contracts.get('states'), 'State machine/backend mismatch')
        rtm = contracts.get('rtm', {})
        require(all(rtm.get(r) for r in self.data['scope']['requirements']), 'Requirement not traced to tests')
        require(all(t in contracts.get('test_ids', []) for tests in rtm.values() for t in tests), 'RTM refers to missing test')
        require(contracts.get('prototype_sha256') == self.document('G2', 'prototype_manifest')['tree_sha256'], 'Prototype/design conflict')
        freeze = self.document('G3', 'freeze')
        require(freeze.get('status') == 'FROZEN' and freeze.get('id') and freeze.get('owner') and freeze.get('time') and freeze.get('commit') == self.stage('G3')['commit'], 'Invalid freeze record')
        refs = freeze.get('files', [])
        require(refs and all(self.ref(r) for r in refs), 'Empty/invalid freeze checksum list')
        expected = {ref['path'] for gate in ('G1', 'G2', 'G3') for name, ref in self.stage(gate)['artifacts'].items() if not (gate == 'G3' and name == 'freeze')}
        require(expected <= {r['path'] for r in refs}, 'Freeze omits design/prototype/API/permission/test artifacts')
        require(not contracts.get('conflicts'), 'Unresolved cross-document conflicts')

    def implementation(self):
        lineage = self.document('G4', 'lineage')
        prototype = self.document('G2', 'prototype_manifest')
        require(lineage.get('prototype_sha256') == prototype['tree_sha256'] and lineage.get('mappings'), 'Prototype source inheritance missing')
        for mapping in lineage['mappings']:
            require(mapping.get('prototype_file') in prototype['files'], 'Unknown inherited prototype file')
            require(mapping.get('prototype_sha256') == prototype['files'][mapping['prototype_file']], 'Prototype lineage hash mismatch')
            self.ref(mapping['implementation'])
        require(set(prototype['page_sources'].values()) <= {m['prototype_file'] for m in lineage['mappings']}, 'Implementation inheritance omits an approved page')
        ui = self.document('G4', 'frozen_ui')
        require(ui.get('files'), 'Frozen UI checksum list missing')
        for ref in ui['files']:
            self.ref(ref)
        require(not ui.get('unapproved_changes'), 'Unapproved UI changes')
        api = self.document('G4', 'real_api')
        require(api.get('backend') == 'http://localhost:8080' and api.get('operations'), 'Real API wiring missing')
        require(not self.document('G4', 'no_mock').get('production_mock_paths', ['unknown']), 'Mock remains in production path')

    def final(self):
        issues = self.document('G5', 'issues')
        for issue in issues.get('items', []):
            if not issue.get('resolved') and (issue.get('blocking') or issue.get('severity') in ('P0', 'P1', 'P2', 'CRITICAL', 'HIGH')):
                # Security exceptions must cite the pre-existing security baseline;
                # the approval cannot invent a new exception policy.
                require(issue.get('severity') in ('CRITICAL', 'HIGH') and issue.get('existing_security_policy'), 'Blocking issue remains')
                self.ref(issue['existing_security_policy'])
                self.approval('G5', issue.get('exception'), 'SECURITY_EXCEPTION')
        visual = self.document('G5', 'visual_comparison')
        require(visual.get('prototype_sha256') == self.document('G2', 'prototype_manifest')['tree_sha256'], 'Wrong visual target')
        require(not visual.get('major_deviations', ['unknown']) and visual.get('pairs'), 'Major visual deviation or comparison missing')
        for pair in visual['pairs']:
            self.ref(pair['prototype'])
            self.ref(pair['formal'])
            require(pair.get('viewport') and pair.get('review'), 'Visual viewport/review missing')
        pages = self.document('G1', 'page_mapping')['pages']
        required_pairs = {(p['id'], v) for p in pages for v in set(p['viewports']) | {1440, 1280, 900, 375}}
        require(required_pairs <= {(p.get('page'), p.get('viewport')) for p in visual['pairs']}, 'Formal screenshot pairs do not cover every page/viewport')
        require(not self.document('G5', 'integration_acceptance').get('unapproved_contract_changes', ['unknown']), 'Unapproved database/API/permission change')

    def check(self, gate):
        self.common(gate)
        require(self.stage(gate)['status'] in ('REVIEW_PENDING', 'ACCEPTED'), f'{gate}: not ready for review')
        self.artifact_checks(gate)
        self.suites(gate)
        simplified = self.data['scope'].get('mode') == 'simplified' and gate in ('G1', 'G2', 'G3')
        if not simplified:
            {'G1': self.design, 'G2': self.prototype, 'G3': self.contracts, 'G4': self.implementation, 'G5': self.final}[gate]()
        self.approval(gate)

    def validate(self, gate, output=None):
        started = time.monotonic()
        errors = []
        try:
            self.check(gate)
        except (GateError, KeyError, ValueError, TypeError, OSError, ET.ParseError) as exc:
            errors.append(str(exc))
        report = {'feature': self.feature, 'gate': gate, 'simulation': self.simulation, 'result': 'FAIL' if errors else 'PASS', 'errors': errors, 'timestamp': now(), 'duration_seconds': round(time.monotonic() - started, 3), 'meaning': 'Evidence and approval validation; not an automated aesthetic judgment'}
        path = Path(output) if output else self.dir / 'evidence' / f'{gate}-gate.json'
        write_json(path, report)
        path.with_suffix('.md').write_text(f'# {self.feature} {gate}: {report["result"]}\n\n' + '\n'.join('- ' + e for e in errors) + '\n\n' + report['meaning'] + '\n', encoding='utf-8')
        return report

    def save(self):
        write_json(self.path, self.data)

    def advance(self, gate, state):
        old = self.stage(gate)['status']
        allowed = {'NOT_STARTED': ('IN_PROGRESS', 'BLOCKED'), 'IN_PROGRESS': ('REVIEW_PENDING', 'BLOCKED', 'REJECTED'), 'REVIEW_PENDING': ('ACCEPTED', 'BLOCKED', 'REJECTED'), 'BLOCKED': ('IN_PROGRESS',), 'REJECTED': ('IN_PROGRESS',), 'ACCEPTED': ()}
        require(state in allowed[old], f'Illegal transition {old} -> {state}; frozen stages require change control')
        if state in ('IN_PROGRESS', 'REVIEW_PENDING', 'ACCEPTED'):
            self.common(gate)
        if state == 'ACCEPTED':
            self.check(gate)
        self.stage(gate)['status'] = state
        self.save()
        return {'feature': self.feature, 'gate': gate, 'from': old, 'to': state}

    def run(self, gate, suite):
        self.common(gate)
        plan = self.stage(gate)['test_plans'][suite]
        require(self.stage(gate)['status'] in ('IN_PROGRESS', 'REVIEW_PENDING'), 'Cannot run tests for unstarted/frozen stage')
        signer_config('evidence', True)
        run_dir = self.dir / 'testing' / (gate + '-' + suite + '-' + uuid.uuid4().hex)
        run_dir.mkdir(parents=True)
        output = run_dir / 'junit.xml'
        argv = [str(a).replace('{python}', sys.executable).replace('{root}', str(self.root)).replace('{junit}', str(output)) for a in plan['argv']]
        env = dict(os.environ, MES_JUNIT_OUTPUT=str(output))
        # The child test process never receives approval/evidence signing secrets.
        env.pop('MES_WORKFLOW_APPROVAL_PRIVATE_KEY', None)
        env.pop('MES_WORKFLOW_EVIDENCE_PRIVATE_KEY', None)
        start_time, start = now(), time.monotonic()
        exit_code = 1
        try:
            proc = subprocess.run(argv, cwd=self.root, env=env, timeout=plan['timeout_seconds'], capture_output=True)
            log = proc.stdout + b'\n' + proc.stderr
            exit_code = proc.returncode
        except (subprocess.TimeoutExpired, OSError) as exc:
            log = str(exc).encode('utf-8')
        log_path = run_dir / 'command.log'
        log_path.write_bytes(log)
        stats = junit(output) if output.exists() else {'tests': 0, 'failed': 1, 'skipped': []}
        files = [p for p in run_dir.rglob('*') if p.is_file()]
        refs = [{'path': p.relative_to(self.root).as_posix(), 'sha256': file_hash(p), 'version': 'run-1'} for p in files]
        payload = {'feature': self.feature, 'gate': gate, 'suite': suite, 'simulation': self.simulation, 'subject': self.subject(gate), 'plan_hash': digest(plan), 'argv': argv, 'started': start_time, 'timestamp': now(), 'duration_seconds': round(time.monotonic() - start, 3), 'exit_code': exit_code, 'result': stats, 'environment': copy.deepcopy(plan.get('runtime', {'kind': plan.get('environment')})), 'outputs': refs, 'junit': next((r for r in refs if r['path'].endswith('/junit.xml')), {})}
        receipt = run_dir / 'receipt.json'
        write_json(receipt, seal(payload, 'evidence'))
        self.stage(gate).setdefault('runs', {})[suite] = receipt.relative_to(self.root).as_posix()
        self.save()
        return payload


def new_manifest(feature):
    return {'schema': 2, 'feature': feature, 'simulation': False, 'scope': {'mode': 'full', 'menu': False, 'baseline': 'FINAL BASELINE COMPLETE v1.0.23', 'ui': 'Global UI V2', 'requirements': [], 'write_paths': []}, 'reads': {}, 'stages': {g: {'status': 'NOT_STARTED', 'version': '1', 'commit': '', 'artifacts': {}, 'source_files': [], 'test_plans': {}, 'runs': {}, 'blockers': [], 'approval': ''} for g in GATES}}


def affected(root, paths):
    root = Path(root)
    manifests = [load_json(p) for p in (root / 'docs/features').glob('*/workflow.yaml')]
    features = set()
    uncovered = []
    for path in paths:
        path = path.replace('\\', '/')
        match = re.match(r'docs/features/([A-Z][A-Z0-9-]+)/', path)
        if match:
            features.add(match[1])
        elif path.startswith(('backend/', 'frontend/', 'mes-demo/')) or path.startswith('docs/ui/'):
            matches = [m['feature'] for m in manifests if any(fnmatch.fnmatchcase(path, pattern) for pattern in m.get('scope', {}).get('write_paths', []))]
            features.update(matches)
            if not matches:
                uncovered.append(path)
    return sorted(features), uncovered


def route_request(request):
    compact = re.sub(r'\s+', '', request).lower()
    explicit = '$mes-feature-workflow' in compact or '使用mes标准流程' in compact or '按mes标准流程' in compact
    kind = 'template' if any(t in compact for t in ('模板', 't1', 't2', 't3', 't4', 't5', 't6')) else 'menu' if '菜单' in compact else 'feature'
    return {'invoked': explicit, 'skill': 'mes-feature-workflow' if explicit else None, 'scope_kind': kind if explicit else None, 'stages': list(GATES) if explicit else [], 'action': 'read-baseline-first' if explicit else 'existing-project-rules-only', 'platform_alias_registered': False}


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('init', 'validate-workflow', 'advance', 'run-evidence', 'subject', 'sign-approval', 'ci', 'route-request'))
    parser.add_argument('--request')
    parser.add_argument('--feature')
    parser.add_argument('--gate', choices=GATES)
    parser.add_argument('--state', choices=STATES)
    parser.add_argument('--suite')
    parser.add_argument('--approver')
    parser.add_argument('--source')
    parser.add_argument('--decision', choices=('ACCEPTED', 'SIMPLIFICATION', 'PROTOTYPE_HASH_EXCEPTION', 'SKIP_EXCEPTION', 'SECURITY_EXCEPTION'), default='ACCEPTED')
    parser.add_argument('--details')
    parser.add_argument('--output')
    parser.add_argument('--changed-files')
    args = parser.parse_args(argv)
    try:
        if args.command == 'route-request':
            require(args.request, '--request required')
            print(json.dumps(route_request(args.request), ensure_ascii=False))
            return 0
        if args.command == 'ci':
            require(args.changed_files, '--changed-files required')
            paths = Path(args.changed_files).read_text(encoding='utf-8').splitlines()
            features, uncovered = affected(root, paths)
            reports = []
            errors = [f'Changed business/UI path has no registered task scope: {p}' for p in uncovered]
            for feature in features:
                wf = Workflow(root, feature)
                declared = {ref['path'] for gate in GATES for ref in wf.stage(gate).get('source_files', [])}
                changed = [p for p in paths if p.startswith(('backend/', 'frontend/', 'mes-demo/', 'docs/ui/')) and any(fnmatch.fnmatchcase(p, pattern) for pattern in wf.data.get('scope', {}).get('write_paths', []))]
                errors.extend(f'Changed implementation file is not bound to evidence: {p}' for p in changed if p not in declared)
                # Merging a new/changed feature requires the entire ordered acceptance chain.
                report = wf.validate('G5')
                reports.append(report)
                if report['result'] != 'PASS':
                    errors.extend(report['errors'])
            result = {'features': features, 'uncovered': uncovered, 'result': 'FAIL' if errors else 'PASS', 'errors': errors, 'gates': reports}
            if args.output:
                write_json(args.output, result)
            print(json.dumps(result, ensure_ascii=False))
            return 1 if errors else 0
        require(args.feature, '--feature required')
        if args.command == 'init':
            require(re.fullmatch(r'[A-Z][A-Z0-9-]{2,63}', args.feature), 'Invalid feature ID')
            directory = Path(root) / 'docs/features' / args.feature
            require(not directory.exists(), 'Feature already exists; never overwrite')
            for name in ('design', 'prototype', 'baseline', 'implementation', 'testing', 'evidence'):
                (directory / name).mkdir(parents=True)
            write_json(directory / 'workflow.yaml', new_manifest(args.feature))
            template = Path(root) / 'docs/templates/FEATURE_TASK_TEMPLATE.md'
            (directory / 'TASK.md').write_text(template.read_text(encoding='utf-8').replace('<FEATURE_ID>', args.feature), encoding='utf-8')
            print(f'Created {directory}; NOT_STARTED; no business approval or development')
            return 0
        require(args.gate, '--gate required')
        wf = Workflow(root, args.feature)
        if args.command == 'validate-workflow':
            report = wf.validate(args.gate, args.output)
            print(json.dumps(report, ensure_ascii=False))
            return 0 if report['result'] == 'PASS' else 1
        if args.command == 'advance':
            require(args.state, '--state required')
            print(json.dumps(wf.advance(args.gate, args.state)))
        elif args.command == 'run-evidence':
            require(args.suite, '--suite required')
            report = wf.run(args.gate, args.suite)
            print(json.dumps({'feature': args.feature, 'gate': args.gate, 'suite': args.suite, 'exit_code': report['exit_code'], 'result': report['result']}))
            return 0 if report['exit_code'] == 0 and report['result']['failed'] == 0 else 1
        elif args.command == 'subject':
            print(wf.subject(args.gate))
        elif args.command == 'sign-approval':
            require(args.approver and args.source and args.output, 'Authorized operator must supply approver/source/output')
            source = wf.resolve(args.source)
            details = load_json(wf.resolve(args.details)) if args.details else {}
            require(set(details) <= {'suite', 'cases', 'reason', 'delegation_source'}, 'Approval details contain reserved/unknown fields')
            payload = {'feature': args.feature, 'gate': args.gate, 'decision': args.decision, 'authority': 'human', 'approver': args.approver, 'subject': wf.subject(args.gate), 'timestamp': now(), 'simulation': False, 'source': {'path': args.source, 'version': '1', 'sha256': file_hash(source)}, **details}
            write_json(args.output, seal(payload, 'approval'))
            print('Signed approval; set stage.approval to this repository-relative record. This does not create human authorization.')
        return 0
    except (GateError, KeyError, ValueError, TypeError, OSError, ET.ParseError) as exc:
        report = {'result': 'FAIL', 'errors': [str(exc)]}
        if args.output:
            write_json(args.output, report)
            Path(args.output).with_suffix('.md').write_text('# FAIL\n\n' + str(exc) + '\n', encoding='utf-8')
        print(json.dumps(report, ensure_ascii=False))
        return 1


if __name__ == '__main__':
    sys.exit(main())
