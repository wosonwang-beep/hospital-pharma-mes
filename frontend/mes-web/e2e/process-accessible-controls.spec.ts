import {test,expect} from '@playwright/test'
test.use({channel:'chrome'})
test('query, process editor and product picker controls expose names and state',async({page})=>{
 test.setTimeout(50000)
 await page.goto('/login')
 if(new URL(page.url()).pathname==='/login'){
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill('admin')
  await page.getByRole('button',{name:/登\s*录/}).click()
  await page.waitForURL(u=>u.pathname!=='/login',{timeout:15000})
 }
 await page.goto('/process/packages')
 await page.getByRole('row').filter({hasText:'KCL30-CPP-26110601'}).waitFor({timeout:15000})
 console.log('LIST_SELECT_ACCESSIBLE='+JSON.stringify(await page.locator('main.process-package-list [role=combobox]').evaluateAll(ns=>ns.map(n=>({outer:n.outerHTML.slice(0,300),labelledby:n.getAttribute('aria-labelledby'),label:n.getAttribute('aria-label')})))))
 console.log('LIST_COMBO_ACCESSIBLE_NAMES='+JSON.stringify({status:await page.getByRole('combobox',{name:'状态'}).count(),product:await page.getByRole('combobox',{name:'适用产品',exact:true}).count()}))
 console.log('LIST_AX='+String(await page.locator('main.process-package-list .query-card').ariaSnapshot()).slice(0,1800))
 await expect(page.locator('main.process-package-list .table-footer [role="status"]')).toContainText('共 9 条')
 await page.goto('/process/packages/829/edit')
 await page.locator('.basic-card').waitFor()
 const tabs=page.locator('.process-workspace-tabs button')
 await expect(tabs).toHaveCount(2)
 await tabs.nth(1).click()
 const picker=page.getByRole('button',{name:/选择产品/}).last()
 await picker.click()
 const dialog=page.getByRole('dialog',{name:'选择适用产品'})
 await expect(dialog).toBeVisible()
 console.log('PICKER_SEARCH_ACCESSIBLE='+JSON.stringify(await dialog.locator('[role=combobox]').evaluateAll(ns=>ns.map(n=>({html:n.outerHTML.slice(0,400),label:n.getAttribute('aria-label'),ariaLabelledby:n.getAttribute('aria-labelledby')})))))
 console.log('PICKER_AX='+String(await dialog.ariaSnapshot()).slice(0,1700))
 console.log('PICKER_NAMED_COMBO='+await dialog.getByRole('combobox',{name:'适用产品',exact:true}).count())
 const combo=dialog.getByRole('combobox',{name:'适用产品',exact:true})
 await expect(combo).toBeVisible()
 console.log('PICKER_ARIA_EXPANDED='+await combo.getAttribute('aria-expanded'))
 await combo.click()
 console.log('PICKER_ARIA_EXPANDED_OPEN='+await combo.getAttribute('aria-expanded'))
 await expect(combo).toHaveAttribute('aria-expanded','true')
 await expect(dialog.getByRole('button',{name:/确\s*认/})).toBeVisible()
 await dialog.getByRole('button',{name:/取\s*消/}).click()
 await expect(dialog).toBeHidden()
})