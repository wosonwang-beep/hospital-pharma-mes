import {test,expect} from '@playwright/test'
test.use({channel:'chrome'})
test('formal process status update is available as a programmatic polite live region',async({page})=>{
  test.setTimeout(55000)
  await page.goto('/login')
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill('admin')
  await page.getByRole('button',{name:/登\s*录/}).click()
  await page.waitForURL(u=>u.pathname!=='/login',{timeout:20000})
  await page.goto('/process/packages/829/edit')
  await page.locator('main.process-page .basic-card').waitFor()
  const field=page.getByRole('textbox',{name:'工艺名称'})
  const original=await field.inputValue()
  const status=page.locator('.workspace-footer [role=status]')
  await expect(status).toHaveAttribute('aria-live','polite')
  await expect(status).toHaveAttribute('aria-atomic','true')
  const session=await page.context().newCDPSession(page)
  await session.send('Accessibility.enable')
  const getAX=async()=>{
    const tree=await session.send('Accessibility.getFullAXTree')
    return tree.nodes.filter((n:any)=>n.role?.value==='status').map((n:any)=>({
      ignored:n.ignored,role:n.role?.value,name:n.name?.value,
      properties:(n.properties||[]).filter((x:any)=>['live','atomic','relevant'].includes(x.name)).map((x:any)=>[x.name,x.value?.value])
    }))
  }
  await expect(status).toContainText('当前配置已生效')
  const before=await getAX()
  expect(before.some(x=>x.ignored===false&&x.properties.some(p=>p[0]==='live'&&p[1]==='polite'))).toBeTruthy()
  await field.fill(original+'（阶段性记录）')
  await expect(status).toContainText('有未保存的修改')
  const during=await getAX()
  console.log('AX_STATUS_NODES_BEFORE_AND_DURING='+JSON.stringify({before,during}))
  const allNodes=(await session.send('Accessibility.getFullAXTree')).nodes
  console.log('AX_STATUS_TEXT_NODES='+JSON.stringify(allNodes.filter((n:any)=>String(n.name?.value||'').includes('有未保存的修改')).map((n:any)=>({role:n.role?.value,name:n.name?.value,ignored:n.ignored,parentId:n.parentId}))))
  expect(allNodes.some((n:any)=>n.ignored===false&&String(n.name?.value||'').includes('有未保存的修改'))).toBeTruthy()
  await field.fill(original)
  await expect(status).toContainText('当前配置已生效')
  const after=await getAX()
  console.log('FORMAL_AX_POLITE_STATUS='+JSON.stringify({before,during,after,networkWrites:0}))
  await session.detach()
  // No save requested; the original business record is untouched.
})

