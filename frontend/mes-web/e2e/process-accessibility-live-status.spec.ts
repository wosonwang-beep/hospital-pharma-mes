 await expect(status).toContainText(/共\s*\d+\s*条/)
 await expect(status).toHaveAttribute('aria-live','polite')
 await expect(status).toHaveAttribute('aria-atomic','true')
 const before=await status.innerText()
 const keyword=page.locator('main.process-package-list .query-form input').first()
 await keyword.fill('KCL30-CPP-26110601')
 await page.locator('main.process-package-list .query-form button[type=submit]').click()
 await expect(status).toContainText('共 1 条')
 const session=await page.context().newCDPSession(page)
 await session.send('Accessibility.enable')
 const tree=await session.send('Accessibility.getFullAXTree')
 const names=tree.nodes.filter((n:any)=>n.ignored===false&&['StaticText','status'].includes(n.role?.value)).map((n:any)=>({role:n.role?.value,name:n.name?.value,props:n.properties}))
 expect(names.some(x=>String(x.name).includes('共 1 条'))).toBeTruthy()
