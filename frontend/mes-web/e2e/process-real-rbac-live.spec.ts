import {test,expect} from '@playwright/test'
test.use({channel:'chrome'})
test('actual local role is denied production process detail by server',async({page})=>{
 test.setTimeout(35000)
 await page.goto('/login')
 const loginResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/v1/auth/login'&&r.request().method()==='POST')
 await page.getByLabel('账号').fill('demo.warehouse')
 await page.getByLabel('密码').fill('DemoUser@2026')
 await page.getByRole('button',{name:/登\s*录/}).click()
 const login=await loginResponse
 expect(login.status()).toBe(200)
 const token=(await login.json()).data?.accessToken as string
 expect(token).toBeTruthy()
 const meResponse=await page.request.get('http://127.0.0.1:5173/api/v1/auth/me',{headers:{Authorization:'Bearer '+token}})
 expect(meResponse.status()).toBe(200)
 const me=(await meResponse.json()).data
 expect(me.permissionCodes).not.toContain('process:package:view')
 const denied=await page.request.get('http://127.0.0.1:5173/api/v1/process-packages/829',{headers:{Authorization:'Bearer '+token}})
 console.log('REAL_ROLE_DENIAL='+JSON.stringify({login:me.loginName,permissions:me.permissionCodes.length,processStatus:denied.status()}))
 expect(denied.status()).toBe(403)
 await page.goto('/process/packages/829')
 await page.waitForTimeout(750)
 expect(new URL(page.url()).pathname).not.toBe('/process/packages/829')
})
test('real duplicate process code fails without losing user input',async({page})=>{
 test.setTimeout(35000)
 await page.goto('/login')
 await page.getByLabel('账号').fill('admin')
 await page.getByLabel('密码').fill('admin')
 await page.getByRole('button',{name:/登\s*录/}).click()
 await page.waitForURL(u=>u.pathname!=='/login',{timeout:15000})
 await page.goto('/process/packages/create')
 await page.getByRole('heading',{name:'新增生产工艺'}).waitFor()
 const code=page.getByLabel('工艺编码')
 const name=page.getByLabel('工艺名称')
 await code.fill('KCL30-CPP-26110601')
 await name.fill('氯化钾溶液配制关键参数控制工艺')
 const conflict=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/v1/process-packages'&&r.request().method()==='POST')
 await page.getByRole('button',{name:'创建生产工艺'}).click()
 const response=await conflict
 console.log('REAL_DUPLICATE_STATUS='+response.status())
 expect(response.status()).toBe(409)
 await expect(page.locator('#process-save-errors')).toContainText('工艺编码已存在')
 await expect(page.getByText('记录已发生变化，输入已保留。重新加载将放弃本地修改，请核对后继续。')).toHaveCount(0)
 await expect(code).toHaveValue('KCL30-CPP-26110601')
 await expect(name).toHaveValue('氯化钾溶液配制关键参数控制工艺')
 expect(new URL(page.url()).pathname).toBe('/process/packages/create')
})
