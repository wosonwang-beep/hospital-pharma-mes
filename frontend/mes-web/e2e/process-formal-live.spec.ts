test('G5: PC process footer never obscures the operation form table',async({page})=>{
 test.setTimeout(60000)
 await page.goto('/login')
 if(new URL(page.url()).pathname==='/login'){
   await page.getByLabel('账号').fill('admin')
   await page.getByLabel('密码').fill('admin')
   await page.getByRole('button',{name:/登\s*录/}).click()
   await page.waitForURL(url=>url.pathname!=='/login',{timeout:15000})
 }
 for(const width of [1440,1280,900]){
   await page.setViewportSize({width,height:900})
   await page.goto('/process/packages/829/edit')
   await page.locator('.process-form-card').waitFor({timeout:12000})
   const value=await page.evaluate(()=>{
     const footer=document.querySelector('.workspace-footer')!.getBoundingClientRect()
     const card=document.querySelector('.process-form-card')!.getBoundingClientRect()
     const body=document.documentElement
     return {footerTop:Math.round(footer.top),cardBottom:Math.round(card.bottom),bodyWidth:body.scrollWidth,viewport:body.clientWidth}
   })
   console.log('FOOTER_GEOMETRY='+JSON.stringify({width,...value}))
   expect(value.footerTop,{message:'Footer must be below form card, never on top of it'}).toBeGreaterThanOrEqual(value.cardBottom)
   expect(value.bodyWidth).toBeLessThanOrEqual(value.viewport+1)
 }
})
